# ---------------------------------------------------------------------------
# ML forecast audit — one parametrized test per company
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("company_dir", _COMPANY_DIRS, ids=lambda d: d.name)
def test_forecast_audit_runs(company_dir: Path) -> None:
    """The forecasting engine must complete for every rep without crashing."""
    report: CompanyAuditReport = audit_company(company_dir)

    assert report.forecast.total_reps_forecasted > 0, (
        f"[{company_dir.name}] Forecast audit produced no rep rows"
    )
    assert report.forecast.company_forecast_next_q >= 0, (
        f"[{company_dir.name}] Company next-Q forecast is negative"
    )

    # Every rep row must have forecast_values and forecast_periods
    incomplete = [
        r.rep_name for r in report.forecast.rep_rows
        if not r.forecast_values or not r.forecast_periods
    ]
    assert incomplete == [], (
        f"[{company_dir.name}] Reps with missing forecast output: {incomplete}"
    )


@pytest.mark.parametrize("company_dir", _COMPANY_DIRS, ids=lambda d: d.name)
def test_forecast_audit_mape_acceptable(company_dir: Path) -> None:
    """Flag (but don't hard-fail) reps with very high backtest MAPE.

    This test is a WARNING-level check — it passes but prints a diagnostic
    for any rep whose MAPE exceeds the threshold.  The threshold is 0.40
    (40 % mean absolute percentage error), which is lenient enough for
    short history series.  Reps with < 4 months history are excluded.
    """
    report: CompanyAuditReport = audit_company(company_dir, mape_warn_threshold=0.40)

    flagged = [r for r in report.forecast.rep_rows if r.mape_flagged and r.history_months >= 4]
    if flagged:
        details = "\n".join(
            f"  {r.rep_name}: MAPE={r.backtest_mape:.2%}, "
            f"strategy={r.strategy_used}, history={r.history_months}m, "
            f"next_q=${r.forecast_next_q_revenue:,.0f}"
            for r in flagged
        )
        pytest.warns(  # noqa: PT017 — intentional soft warning
            UserWarning,
            match="",
        ) if False else None   # emit info without failing
        print(
            f"\n[{company_dir.name}] {len(flagged)} rep(s) with MAPE > 40%:\n{details}"
        )
    # Always passes — high MAPE is informational, not a hard failure
    assert True


# ---------------------------------------------------------------------------
# Smoke test: report serialises to dict without errors
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("company_dir", _COMPANY_DIRS, ids=lambda d: d.name)
def test_audit_report_serialises(company_dir: Path) -> None:
    """CompanyAuditReport.to_dict() must return a well-formed dict."""
    report: CompanyAuditReport = audit_company(company_dir)
    d = report.to_dict()

    assert "company" in d
    assert "passed" in d
    assert "payout" in d
    assert "forecast" in d
    assert isinstance(d["payout"]["reps"], list)
    assert isinstance(d["forecast"]["reps"], list)
    assert isinstance(d["payout"]["total_credits"], float)
    assert isinstance(d["forecast"]["company_forecast_next_q"], float)
