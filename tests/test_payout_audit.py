"""
tests/test_payout_audit.py
===========================
Automated payout-math + ML forecast audit for every company under companies/.

CI gate: strict payout tests (no_bugs, plan_coverage) run only for FULL companies
— those generated by data_generator.py that include payouts.csv.  Companies
without payouts.csv (legacy or partially-generated datasets) are skipped for
those two tests but still audited for forecast smoke tests.

Quota-exempt leadership roles (CRO/SVP/VP) are skipped automatically.

Discovery: the test parametrizes over every subdirectory of companies/ that
contains the four required CSV files.  Adding a new company automatically
adds it to the test suite — no manual registration needed.
"""
from __future__ import annotations

from pathlib import Path

import pytest

from backend.audit.payout_audit import (
    audit_company,
    CompanyAuditReport,
    QUOTA_EXEMPT_ROLES,
)

# ---------------------------------------------------------------------------
# Company discovery
# ---------------------------------------------------------------------------

_REQUIRED_CSVS = {"reps.csv", "deals.csv", "revenue.csv", "quotas.csv"}


def _get_company_dirs() -> list[Path]:
    base = Path("companies")
    if not base.exists():
        return []
    dirs = []
    for entry in sorted(base.iterdir()):
        if not entry.is_dir():
            continue
        csvs = {f.name for f in entry.glob("*.csv")}
        if _REQUIRED_CSVS.issubset(csvs):
            dirs.append(entry)
    return dirs


_COMPANY_DIRS = _get_company_dirs()

# Companies with full generated schema (payouts.csv present) — strict CI gate
_FULL_COMPANY_DIRS = [d for d in _COMPANY_DIRS if (d / "payouts.csv").exists()]


# ---------------------------------------------------------------------------
# Payout math audit — one parametrized test per company
# ---------------------------------------------------------------------------

@pytest.mark.parametrize("company_dir", _FULL_COMPANY_DIRS, ids=lambda d: d.name)
def test_payout_audit_no_bugs(company_dir: Path) -> None:
    """Every quota-carrying rep must have: plan, rules, revenue, ≥1 closed-won deal,
    non-zero payout, and stored payout within $1 of engine-derived payout.

    Only runs for companies with payouts.csv (data_generator output).
    Legacy or partially-generated companies are excluded from this gate."""
    report: CompanyAuditReport = audit_company(company_dir)

    buggy = [
        r for r in report.payout.payout_rows
        if r.bugs and not r.status.startswith("EXEMPT")
    ]

    assert buggy == [], (
        f"[{company_dir.name}] {len(buggy)} rep(s) have payout bugs:\n"
        + "\n".join(
            f"  {r.rep_name}: {r.bugs}  "
            f"(quota=${r.quota:,.0f}, rev=${r.revenue:,.0f}, "
            f"csv_payout=${r.csv_payout:,.2f}, engine=${r.engine_payout:,.2f})"
            for r in buggy
        )
    )


@pytest.mark.parametrize("company_dir", _FULL_COMPANY_DIRS, ids=lambda d: d.name)
def test_payout_audit_plan_coverage(company_dir: Path) -> None:
    """Every plan that has reps assigned must have at least 4 commission rules.

    Only runs for companies with payouts.csv (data_generator output)."""
    report: CompanyAuditReport = audit_company(company_dir)

    thin_plans = {
        plan_id: info
        for plan_id, info in report.payout.plan_coverage.items()
        if info["rules"] < 4
    }

    assert thin_plans == {}, (
        f"[{company_dir.name}] Plans with fewer than 4 rules: "
        + ", ".join(
            f"{info['external_id']} ({info['rules']} rules, {info['reps']} reps)"
            for info in thin_plans.values()
        )
    )


